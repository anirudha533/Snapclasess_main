begin;

create table public.teachers (
    teacher_id bigint generated by default as identity primary key,
    name text not null,
    username varchar not null unique,
    auth_user_id uuid unique references auth.users (id) on delete set null
);

create table public.students (
    student_id bigint generated by default as identity primary key,
    name text not null,
    face_embedding jsonb check (jsonb_typeof(face_embedding) = 'array'),
    voice_embedding jsonb check (jsonb_typeof(voice_embedding) = 'array')
);

create table public.subjects (
    subject_id bigint generated by default as identity primary key,
    subject_code text not null,
    name text default 'UNKNOWN',
    section text default 'N/A',
    teacher_id bigint references public.teachers (teacher_id) on delete set null
);

create table public.subject_students (
    subject_id bigint references public.subjects (subject_id) on delete cascade,
    student_id bigint references public.students (student_id) on delete cascade,
    primary key (subject_id, student_id)
);

create table public.attendance_logs (
    id bigint generated by default as identity primary key,
    "timestamp" timestamptz not null default now(),
    subject_id bigint not null references public.subjects (subject_id),
    student_id bigint not null references public.students (student_id)
);

create index subjects_teacher_id_idx on public.subjects (teacher_id);
create index subject_students_student_id_idx on public.subject_students (student_id);
create index attendance_logs_subject_id_idx on public.attendance_logs (subject_id);
create index attendance_logs_student_id_idx on public.attendance_logs (student_id);

alter table public.teachers enable row level security;
alter table public.students enable row level security;
alter table public.subjects enable row level security;
alter table public.subject_students enable row level security;
alter table public.attendance_logs enable row level security;

-- Start with administrator-only access until application roles are defined.
revoke all on public.teachers, public.students, public.subjects,
    public.subject_students, public.attendance_logs
    from public, anon, authenticated;

commit;
